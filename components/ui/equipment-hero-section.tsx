export function EquipmentHeroSection() {
  const reducedMotion = useReducedMotion();

  /** Which rendering to mount. Deliberately null until after mount and
   * resolved from matchMedia rather than from a render-time hook: a hook
   * that server-renders as `false` would have every phone start pulling the
   * desktop frame set during hydration before correcting itself, and a
   * laptop start fetching the video. Nothing loads until this is known.
   *
   * The two are separate components rather than one with a branch inside,
   * so crossing the breakpoint unmounts the whole of the previous one —
   * there is no path where a video keeps decoding behind a canvas, or a
   * scroll loop keeps measuring a container that is now one viewport tall. */
  const [variant, setVariant] = useState<Variant | null>(null);

  useEffect(() => {
    const mql = window.matchMedia(`(max-width: ${MOBILE_BREAKPOINT}px)`);
    const apply = () => setVariant(mql.matches ? "mobile" : "desktop");
    apply();
    mql.addEventListener("change", apply);
    return () => mql.removeEventListener("change", apply);
  }, []);

  // Server-rendered, and on screen for the one frame before matchMedia
  // resolves: the container and its spacer, nothing that loads. It carries
  // the height the real hero will have — six viewports on a laptop, one on
  // a phone, decided by the stylesheet at the same breakpoint — so the page
  // below it does not jump when the rendering swaps in. Preloader.tsx finds
  // .hero-container here too, which is why it keys on that rather than on
  // anything inside.
  if (!variant) {
    return (
      <div className="hero-container is-pending">
        <div className="hero-scroll-spacer" aria-hidden />
      </div>
    );
  }
  return variant === "mobile" ? (
    <HeroLoop reducedMotion={reducedMotion} />
  ) : (
    <HeroScrub reducedMotion={reducedMotion} />
  );
}
