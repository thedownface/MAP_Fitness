/** Opacity and lift for one beat, windowed on its pass of the video. Same
 * shape as useBeatMotion, driven by the clip's clock instead of the
 * scrollbar. */
function useLoopBeat(phase: MotionValue<number>, window: LoopWindow, reducedMotion: boolean) {
  const f = LOOP_FADE;
  // The first window starts at the cycle's own origin, so it has nothing
  // before it to fade across — it rises from zero as the cycle restarts.
  // That leaves a fraction of a second at the wrap with the copy at its
  // dimmest, which is deliberate: it lands on the frame where the footage
  // cuts, so the two read as one change rather than as a gap.
  const inFrom = window.from === 0 ? 0 : window.from - f;
  const inTo = window.from === 0 ? f * 2 : window.from + f;
  const opacity = useTransform(phase, [inFrom, inTo, window.to - f, window.to + f], [0, 1, 1, 0]);
  const rawY = useTransform(phase, [inFrom, inTo], [26, 0]);
  const y = useTransform(rawY, (v) => (reducedMotion ? 0 : v));
  const visibility = useTransform(opacity, (v) => (v <= 0.001 ? "hidden" : "visible"));
  return { opacity, y, visibility };
}

/** Mobile: the clip on a loop, with the copy advancing one beat per pass.
 *
 * Nothing here is scroll-linked. The hero is one ordinary viewport-tall
 * section, so scrolling past it is just scrolling, and the moving image
 * costs the main thread nothing — decoding and compositing a video is the
 * one job a phone does entirely in hardware. */
function HeroLoop({ reducedMotion }: { reducedMotion: boolean }) {
  const videoRef = useRef<HTMLVideoElement>(null);
  const entered = useHasMounted() || reducedMotion;
  const phase = useMotionValue(0);
  const windows = useMemo(() => buildLoopWindows(MOBILE.chapters), []);

  const beat0 = useLoopBeat(phase, windows[1], reducedMotion);
  const beat1 = useLoopBeat(phase, windows[2], reducedMotion);
  const beat2 = useLoopBeat(phase, windows[3], reducedMotion);
  const beat3 = useLoopBeat(phase, windows[4], reducedMotion);
  const beatMotions = [beat0, beat1, beat2, beat3];

  // The h1 holds the loop's first window and leaves the way the beats do.
  const introOpacity = useTransform(
    phase,
    [windows[0].to - LOOP_FADE, windows[0].to + LOOP_FADE],
    [1, 0],
  );
  const introVisibility = useTransform(introOpacity, (v) => (v <= 0.001 ? "hidden" : "visible"));

  useEffect(() => {
    const video = videoRef.current;
    if (!video) return;

    // Set on the element as well as in JSX: `muted` is the condition every
    // browser puts on inline autoplay, and React has historically not
    // reflected it to the attribute in time for the first play attempt.
    video.muted = true;
    video.defaultMuted = true;

    // playbackRate is reset by a load, so it is reapplied on every
    // loadedmetadata rather than set once.
    const applyRate = () => {
      video.playbackRate = reducedMotion ? 1 : LOOP_RATE;
    };
    applyRate();
    video.addEventListener("loadedmetadata", applyRate);

    let announced = false;
    const announce = () => {
      if (announced) return;
      announced = true;
      window.dispatchEvent(new Event("map:hero-ready"));
    };
    video.addEventListener("loadeddata", announce);
    // Announce regardless if the video never gets there, so a phone that
    // refuses to load it does not sit behind the preloader.
    const fallbackReady = window.setTimeout(announce, 4000);
    if (video.readyState >= 2) announce();

    if (!reducedMotion) {
      // iOS Low Power Mode refuses inline autoplay even when muted. There
      // is nothing to do about that except not depend on it: the poster
      // stays up, and the clock below keeps the copy cycling, so the hero
      // still reads as a hero rather than a frozen image with one line on
      // it.
      void video.play().catch(() => {});
    }

    /** The cycle's clock: which pass of the video we are on, plus how far
     * through it — so `phase` runs 0..1 across all five passes, one beat
     * per pass.
     *
     * Counted off the video rather than off a timer so the copy advances in
     * the same instant the footage cuts, every time, with no drift to
     * accumulate over a visit. A pass is over when currentTime goes
     * backwards; the tolerance is there because a looping video reports a
     * currentTime that can jitter by a frame either way around the wrap,
     * and a bare `t < last` would count some of those as extra passes.
     *
     * Wall time takes over when the video is not actually playing (iOS Low
     * Power Mode, a backgrounded tab, reduced motion holding the poster) so
     * the copy still cycles over the poster rather than stranding whichever
     * beat happened to be up. */
    const passes = MOBILE.chapters.length;
    const started = performance.now();
    const cycleMs = ((video.duration || 8) * 1000 * passes) / (reducedMotion ? 1 : LOOP_RATE);
    let pass = 0;
    let lastTime = 0;
    let raf = 0;
    const tick = () => {
      raf = requestAnimationFrame(tick);
      if (!reducedMotion && !video.paused && video.duration > 0) {
        const t = video.currentTime;
        if (t < lastTime - 0.1) pass = (pass + 1) % passes;
        lastTime = t;
        phase.set((pass + t / video.duration) / passes);
        return;
      }
      phase.set(((performance.now() - started) / cycleMs) % 1);
    };
    raf = requestAnimationFrame(tick);

    return () => {
      cancelAnimationFrame(raf);
      window.clearTimeout(fallbackReady);
      video.removeEventListener("loadedmetadata", applyRate);
      video.removeEventListener("loadeddata", announce);
    };
  }, [reducedMotion, phase]);

  const crop = MOBILE.crop;
  const plate = MOBILE.plate;

  return (
    <div
      className="hero-container is-loop"
      style={
        {
          "--hero-diagonal-left": `${MOBILE_DIAGONAL_LEFT * 100}%`,
          "--hero-diagonal-right": `${MOBILE_DIAGONAL_RIGHT * 100}%`,
          // The band the athlete stands in, reproducing in CSS exactly what
          // the desktop canvas does in drawImage: size him off the viewport
          // width, cap that against viewport height so he stays clear of the
          // diagonal (MOBILE_MAX_HEIGHT), and stand his feet on
          // MOBILE_FEET_Y rather than centring the band — which is what
          // keeps the floor line still while his pose changes on top of it.
          "--band-h": `min(${(100 * crop.height) / crop.width}vw, ${MOBILE_MAX_HEIGHT * 100}vh)`,
          "--band-w": `calc(var(--band-h) * ${crop.width / crop.height})`,
          "--band-top": `calc(${MOBILE_FEET_Y * 100}% - ${MOBILE.groundY} * var(--band-h))`,
          // The video is the *uncropped* clip, so it is wider than the band
          // and overflows it on both sides — that overflow is the crop. The
          // nudge re-centres it on the crop's own centre rather than the
          // frame's, the 4px that made the difference between him being
          // centred on a phone and sitting slightly left of it.
          "--video-w": `calc(var(--band-h) * ${crop.source.width / crop.source.height})`,
          "--video-dx": `calc(var(--video-w) * ${
            (crop.source.width / 2 - (crop.left + crop.width / 2)) / crop.source.width
          })`,
          "--plate-top": plate[0],
          "--plate-bottom": plate[1],
        } as React.CSSProperties
      }
    >
      <div className="hero-loop-plate" aria-hidden>
        <div className="hero-loop-band">
          <video
            ref={videoRef}
            className="hero-video"
            src={HERO_VIDEO}
            poster={MOBILE.posterSrc}
            preload="auto"
            loop
            muted
            playsInline
            autoPlay={!reducedMotion}
            disablePictureInPicture
            tabIndex={-1}
          />
        </div>
      </div>

      {BEATS.map((beat, i) => (
        <motion.div
          key={beat.key}
          className="hero-beat"
          style={{ opacity: beatMotions[i].opacity, visibility: beatMotions[i].visibility }}
        >
          <span className="hero-beat-numeral font-display" aria-hidden>
            {beat.index}
          </span>
          <motion.div className="hero-beat-inner" style={{ y: beatMotions[i].y }}>
            <BeatCopy beat={beat} />
          </motion.div>
        </motion.div>
      ))}

      <motion.div
        className="hero-content"
        style={{ opacity: introOpacity, visibility: introVisibility }}
      >
        <HeroHeadline entered={entered} reducedMotion={reducedMotion} />
      </motion.div>
    </div>
  );
}

