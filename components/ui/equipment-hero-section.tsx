/** The hero renders the same eight seconds of footage two different ways.
 *
 * Desktop (HeroScrub) scrubs a frame sequence against scroll: the athlete
 * only moves when the page does, and stops dead on a measured pose while
 * each beat's copy is read. That is the whole point of it there — a big
 * screen has the scroll distance to spend and a pointer precise enough to
 * make the scrubbing feel like direct manipulation.
 *
 * Mobile (HeroLoop) plays public/videos/hero-loop.mp4 on a loop instead,
 * with the copy cued off the video's own clock. A phone gets the hero as a
 * moving image it can simply watch rather than one it has to operate, and
 * the page above it is an ordinary 100vh section again — no multi-viewport
 * scroll container, no frame decoding, no per-tick canvas blit. Video
 * playback is the one thing a phone's media pipeline does in dedicated
 * hardware, entirely off the main thread.
 *
 * Both readings share this file's geometry, its copy, and the chapter
 * anchors in the manifests — the same measured poses either hold the scrub
 * still or cue a line of type, so the two never tell different stories.
 *
 * The frame sets themselves are generated by scripts/encode-hero-frames.mjs
 * from the PNG masters in public/athlete/ — see that file for why the
 * masters can't be served directly, and for the more important reason it
 * runs an analysis pass: 61% of the masters are exact duplicates of the
 * frame before them, and scrubbing that judder is what used to read as
 * scroll lag. */
type Chapter = {
  key: string;
  /** The moment this pose arrives, as a fraction of the source clip, 0..1 —
   * what the mobile video loop cues its copy off. Both manifests carry it,
   * which is what keeps the two renderings telling the same story. */
  at: number;
};

/** A chapter in a variant that publishes a frame sequence: `frame` is the
 * index in it that the scrub holds still on. */
type ScrubChapter = Chapter & { frame: number };

type FrameSet = {
  dir: string;
  count: number;
  width: number;
  height: number;
  /** Fraction of the frame's height where his feet meet the floor. */
  groundY: number;
  /** The poses the hero stops on, one per beat. */
  chapters: readonly ScrubChapter[];
  /** Device-pixel-ratio ceiling for the drawing buffer. */
  maxDpr: number;
};

