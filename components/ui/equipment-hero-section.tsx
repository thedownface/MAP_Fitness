/** How fast the clip plays, and how the copy is paced against it.
 *
 * The clip is eight seconds long. Five beats cannot be read in eight
 * seconds — cueing each one to the moment its own pose arrives gives the
 * last of them 0.6s on screen at this rate — so the two are on different
 * cycles: the video loops every clip, and the copy advances one beat per
 * loop. A beat therefore holds for a whole pass of the footage, about six
 * and a half seconds, and the full set of five takes five passes.
 *
 * The trade that buys is worth naming, because an earlier version of this
 * made the opposite one: the copy no longer describes the pose on screen at
 * that instant. It cannot, at a playback rate where the athlete runs his
 * whole routine in the time it takes to read one line. His pose does come
 * round inside the pass its beat is on (the manifest's `at` says where), but
 * the beat is ambient over the loop rather than locked to a frame. The
 * desktop scrub still locks exactly — there, the reader controls the clock.
 *
 * The advance lands on the loop's own restart, so the copy changes in the
 * same instant the footage cuts back to the opening stance. That reads as
 * one deliberate chapter change instead of two unrelated jumps, and it is
 * the reason the phase below is counted off the video rather than a timer. */
const LOOP_RATE = 1.25;
/** Crossfade half-width, as a share of the whole five-pass cycle. */
const LOOP_FADE = 0.01;

type LoopWindow = { from: number; to: number };

/** One window per chapter, each an equal share of the cycle — which is one
 * pass of the video, since the cycle is exactly as many passes as there are
 * chapters. Expressed as a list rather than derived from an index at the
 * call site so the loop and the scrub keep the same shape, and so
 * `npm run hero:timeline` can print and check it. */
function buildLoopWindows(chapters: readonly Chapter[]): LoopWindow[] {
  return chapters.map((_, i) => ({ from: i / chapters.length, to: (i + 1) / chapters.length }));
}

