/** Share of the hero's scroll each chapter spends *held* on its anchor
 * frame, and the share at the end reserved for the fade to black.
 *
 * The holds are the whole point of the rebuild. A linear progress -> frame
 * map never rests on anything: every pose is a frame you are already
 * scrolling away from, so the athlete is permanently a blur in transit and
 * the copy has to be read off a moving background. Stopping him on a
 * measured, sharp frame (see CHAPTERS in scripts/encode-hero-frames.mjs)
 * for a tenth of the hero turns each beat into a held photograph with a
 * line of type beside it, which is the thing that reads as deliberate
 * rather than laggy.
 *
 * Four beats at 0.10 plus the short opening hold below leaves 0.50 for
 * travel. Against the 520vh of scroll range the stylesheet gives the hero
 * that is ~52vh of stillness per beat and ~1.1vh of scroll per frame while
 * he moves — close to the pacing the old linear map had, except now every
 * one of those frames differs from the one before it.
 *
 * Check both with `npm run hero:timeline`, which prints the timeline these
 * produce and fails if the holds collide or his playback rate lurches. */
const DWELL = 0.1;
const OUTRO = 0.07;

/** The opening chapter gets a much shorter hold than the rest, because its
 * hold has mostly already happened: the h1 over the stance frame is what is
 * on screen before a single pixel of scroll, so the reader has had as long
 * as they wanted with it. Giving it a full DWELL would spend the first 52vh
 * of scrolling with the frame held and the h1 pinned — the user drags, and
 * nothing whatsoever moves, which is exactly the "is this broken?" feeling
 * the rest of this work is trying to remove. 0.03 is a short settle so the
 * very first scroll does not jerk straight into motion. */
const INTRO_DWELL = 0.03;

const dwellFor = (i: number) => (i === 0 ? INTRO_DWELL : DWELL);

type Segment = { frame: number; holdStart: number; holdEnd: number };

/** Lays the chapters out along scroll progress, giving each *travel* stretch
 * a share of the leftover scroll proportional to how many frames it has to
 * cross.
 *
 * Proportional rather than equal because the anchors are not evenly spaced
 * in the footage — stance to guard is 81 frames, guard to drive is 27. Equal
 * scroll per gap would play the first stretch at three times the speed of
 * the second, so his apparent playback rate would lurch every time a beat
 * ended. Sharing the budget by frame count instead keeps one constant
 * frames-per-pixel across the whole hero, and derives it from the manifest,
 * so re-encoding the footage re-times the hero rather than silently
 * desyncing it. */
function buildTimeline(chapters: readonly ScrubChapter[]): Segment[] {
  const gaps = chapters
    .slice(1)
    .map((c, i) => Math.max(1, c.frame - chapters[i].frame));
  const totalGap = gaps.reduce((a, b) => a + b, 0);
  const totalDwell = chapters.reduce((sum, _, i) => sum + dwellFor(i), 0);
  const travelBudget = Math.max(0, 1 - OUTRO - totalDwell);

  const segments: Segment[] = [];
  let t = 0;
  chapters.forEach((c, i) => {
    segments.push({ frame: c.frame, holdStart: t, holdEnd: t + dwellFor(i) });
    t += dwellFor(i);
    if (i < gaps.length) t += (travelBudget * gaps[i]) / totalGap;
  });
  return segments;
}

/** Ease with zero slope at both ends, so he decelerates into a pose and
 * accelerates out of it instead of stopping dead and restarting. A hard
 * stop at the hold boundary is what makes a scrub feel broken — the motion
 * has to arrive at rest, not be switched off. */
const smoothstep = (u: number) => u * u * (3 - 2 * u);

/** Scroll progress -> frame index, holding still across each chapter's
 * dwell window and easing between them. */
function frameAtProgress(segments: Segment[], p: number) {
  if (p <= segments[0].holdEnd) return segments[0].frame;
  for (let i = 0; i < segments.length - 1; i++) {
    const a = segments[i];
    const b = segments[i + 1];
    if (p < b.holdStart) {
      const u = (p - a.holdEnd) / (b.holdStart - a.holdEnd);
      return a.frame + (b.frame - a.frame) * smoothstep(u);
    }
    if (p <= b.holdEnd) return b.frame;
  }
  return segments[segments.length - 1].frame;
}

/** The chapter whose hold `p` currently falls in, or is nearest to — used
 * only under reduced motion, where the frame snaps between anchors instead
 * of scrubbing. */
function chapterAtProgress(segments: Segment[], p: number) {
  let best = 0;
  for (let i = 1; i < segments.length; i++) {
    if (p >= segments[i].holdStart - DWELL / 2) best = i;
  }
  return best;
}

