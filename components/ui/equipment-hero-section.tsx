// Horizontal anchor for drawImage's cover-fit crop: 0 = left edge of the
// frame shown, 0.5 = centered, 1 = right edge. The canvas is confined to a
// right-hand column (see the media query on .hero-canvas), so this only
// needs to add a small further nudge, drifted toward as the user scrolls so
// the athlete visibly settles rightward rather than sitting static.
const ANCHOR_BASE = 0.5;
const ANCHOR_MAX = 0.64;
const ANCHOR_SCROLL_WINDOW = 0.06;

function computeAnchorX(progress: number) {
  const t = Math.max(0, Math.min(1, progress / ANCHOR_SCROLL_WINDOW));
  return ANCHOR_BASE + (ANCHOR_MAX - ANCHOR_BASE) * t;
}

