/** Opacity and lift for one beat, windowed on that chapter's hold.
 *
 * The copy resolves while he is decelerating into the pose and is fully up
 * for essentially the whole hold, so the reading happens against a still
 * image rather than a moving one — the sequencing the beats were always
 * meant to have and never got from a window defined in raw scroll
 * fractions.
 *
 * No animated `filter: blur()` any more. It was the single most expensive
 * thing in the hero: three fixed inset:0 layers each re-rasterising a
 * full-viewport blur on every scroll tick, on top of the canvas blit. It
 * also produced the smeared mid-transition text that made the hero look
 * like it was failing to keep up — the blur *was* the lag people were
 * seeing. A short lift and a crossfade give the same softness for the cost
 * of two compositor properties. */
function useBeatMotion(
  progress: MotionValue<number>,
  segment: Segment,
  reducedMotion: boolean,
) {
  const lead = 0.035;
  const tail = 0.03;
  const opacity = useTransform(
    progress,
    [segment.holdStart - lead, segment.holdStart + 0.012, segment.holdEnd - 0.012, segment.holdEnd + tail],
    [0, 1, 1, 0],
  );
  const rawY = useTransform(progress, [segment.holdStart - lead, segment.holdStart + 0.012], [34, 0]);
  const y = useTransform(rawY, (v) => (reducedMotion ? 0 : v));
  // Only the beat that is actually on screen keeps a composited layer.
  // Four fixed, full-viewport layers stacked over the canvas cost real
  // memory and compositing on a phone even at opacity 0.
  const visibility = useTransform(opacity, (v) => (v <= 0.001 ? "hidden" : "visible"));
  return { opacity, y, visibility };
}

/** Desktop: the scroll-scrubbed frame sequence. */
function HeroScrub({ reducedMotion }: { reducedMotion: boolean }) {
  const containerRef = useRef<HTMLDivElement>(null);
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const framesRef = useRef<Array<HTMLImageElement | undefined>>([]);
  const anchorXRef = useRef(ANCHOR_BASE);
  const entered = useHasMounted() || reducedMotion;

  /** Scroll progress through the hero, 0 at the top of the container and 1
   * when its bottom reaches the bottom of the viewport.
   *
   * Driven by the component's own rAF loop below rather than by
   * `useScroll`, and this is the second half of the lag fix. The old chain
   * was: gsap.ticker -> Lenis writes scrollY -> native scroll event ->
   * Framer samples it -> useMotionValueEvent fires -> requestAnimationFrame
   * -> draw. Each arrow is a chance to land in the next frame, and the last
   * one guarantees it, so the athlete was painted at a scroll position the
   * page had already left. On a smooth Lenis scroll that reads exactly like
   * the image lagging behind the page, because it is.
   *
   * Reading the container's own rect inside a rAF collapses all of that:
   * Lenis has already written this frame's scroll position by the time our
   * callback runs (gsap.ticker registers its rAF first, at Lenis init), so
   * the rect is current, and the canvas is drawn from it in the same frame.
   * The beats hang off the same motion value, so type and image can never
   * disagree about where the page is. */
  const progress = useMotionValue(0);

  const segments = useMemo(() => buildTimeline(DESKTOP.chapters), []);

  const pastHeroDisplay = useTransform(progress, (v) => (v >= 1 ? "none" : "block"));
  // The h1 is the `stance` chapter (segments[0]) and leaves the way every
  // other chapter does: held through its dwell, then crossfaded out as the
  // athlete starts to move. It has no fade *in* — it is the first thing on
  // screen, and animates itself in on mount instead (see the render below).
  const introOpacity = useTransform(progress, [segments[0].holdEnd, segments[0].holdEnd + 0.035], [1, 0]);
  const introVisibility = useTransform(introOpacity, (v) => (v <= 0.001 ? "hidden" : "visible"));
  // Picks up exactly where the last beat's fade-out ends (holdEnd + tail),
  // so the blackout continues the dissolve instead of leaving a stretch of
  // bare frame-scrub between "last beat gone" and "next section visible".
  const blackoutOpacity = useTransform(progress, [1 - OUTRO, 1], [0, 1]);

  // Called a fixed 4 times (one per BEATS entry) in the same order every
  // render, same as any other hook — not looped via BEATS.map(), which
  // would make the call count depend on runtime data instead of source
  // order. segments[0] is the opening stance, which has no beat.
  const beat0 = useBeatMotion(progress, segments[1], reducedMotion);
  const beat1 = useBeatMotion(progress, segments[2], reducedMotion);
  const beat2 = useBeatMotion(progress, segments[3], reducedMotion);
  const beat3 = useBeatMotion(progress, segments[4], reducedMotion);
  const beatMotions = [beat0, beat1, beat2, beat3];

  useEffect(() => {
    const set = DESKTOP;
    const canvas = canvasRef.current;
    // alpha:false — every draw fills the whole canvas before blitting the
    // frame, so there is never anything to composite through to the page
    // behind it, and an opaque backing store skips that blend per paint.
    const ctx = canvas?.getContext("2d", { alpha: false });
    const container = containerRef.current;
    if (!canvas || !ctx || !container) return;

    framesRef.current = [];

    /** Match the drawing buffer to the canvas's own rendered CSS box (not
     * window.innerWidth) so it follows whatever width the stylesheet
     * currently gives it — the right-hand wedge the media query on
     * .hero-canvas defines. Deliberately
     * doesn't set canvas.style.width/height: an inline style would outrank
     * that stylesheet rule and pin the box to whichever size was measured
     * first, never picking up a later breakpoint change.
     *
     * Called from the rAF loop rather than from a resize listener, and
     * reports whether it actually resized — assigning canvas.width clears
     * the backing store, so the caller has to know to repaint. Polling the
     * box also covers the cases a resize event misses: the mobile URL bar
     * collapsing, and the CSS box changing at a breakpoint without the
     * window changing size. */
    const syncSize = () => {
      const box = canvas.getBoundingClientRect();
      if (!box.width || !box.height) return false;
      const dpr = Math.min(window.devicePixelRatio || 1, set.maxDpr);
      const w = Math.round(box.width * dpr);
      const h = Math.round(box.height * dpr);
      if (w === canvas.width && h === canvas.height) return false;
      canvas.width = w;
      canvas.height = h;
      return true;
    };
    syncSize();

    /** Cover-fit into the canvas box, anchored horizontally by anchorXRef.
     * The canvas is a tall right-hand wedge, so cropping the 16:9 frame to
     * fill it is the intended composition. */
    const draw = (img: CanvasImageSource, w: number, h: number, cw: number, ch: number) => {
      const scale = Math.max(cw / w, ch / h) * IMAGE_SCALE;
      const dw = w * scale;
      const dh = h * scale;
      ctx.fillStyle = BACKDROP_FALLBACK;
      ctx.fillRect(0, 0, cw, ch);
      ctx.drawImage(img, (cw - dw) * (1 - anchorXRef.current), (ch - dh) / 2, dw, dh);
    };

    const drawFrame = (target: number) => {
      // Scrubbing can outrun the loader. Fall back to the nearest earlier
      // frame that has arrived so the scrub keeps moving instead of
      // freezing on whatever was last painted.
      let index = Math.max(0, Math.min(set.count - 1, target));
      while (index >= 0 && !framesRef.current[index]) index--;
      const img = framesRef.current[index];
      if (!img) return;
      draw(img, img.naturalWidth, img.naturalHeight, canvas.width, canvas.height);
    };
    let cancelled = false;

    /** Decode up front, so no frame is ever decoded for the first time
     * during a scroll.
     *
     * Nothing here used to decode at all: `new Image()` with
     * `decoding = "async"` only permits an off-thread decode, it does not
     * request one, so the first `drawImage` of each frame decoded it
     * synchronously on the main thread — hundreds of first-time decodes
     * landing precisely during the user's first scroll through the hero.
     *
     * HTMLImageElement rather than ImageBitmap: 175 frames at 1280x720 is
     * ~615 MB decoded, far too much to pin as bitmaps. Leaving them as
     * elements lets the browser evict under memory pressure, at the cost of
     * an occasional re-decode — a trade a desktop absorbs and a phone could
     * not, which is one of the reasons mobile plays a video instead. */
    const loadFrame = async (i: number) => {
      if (cancelled || framesRef.current[i]) return;
      try {
        const img = new Image();
        img.decoding = "async";
        img.src = framePath(set.dir, i);
        await img.decode();
        if (cancelled) return;
        framesRef.current[i] = img;
      } catch {
        // A frame that fails to load is skipped, not retried: drawFrame
        // falls back to the nearest earlier frame, so a hole costs a
        // repeated frame rather than a frozen scrub.
      }
    };

    (async () => {
      // Anchors first, in this order: whatever the network is doing, the
      // frames the scrub actually stops on are the ones already decoded, so
      // every hold lands on its sharp photograph rather than on drawFrame's
      // nearest-earlier fallback. The in-between frames only ever flash
      // past.
      await loadFrame(set.chapters[0].frame);
      if (cancelled) return;
      drawFrame(set.chapters[0].frame);
      // Preloader.tsx holds the loader until ".hero-container" exists and
      // this fires; HeroLoop dispatches the same event when its video is
      // ready, so the loader's contract is the same whichever renders.
      window.dispatchEvent(new Event("map:hero-ready"));

      await Promise.all(set.chapters.map((c) => loadFrame(c.frame)));
      if (cancelled) return;

      // Under reduced motion the frame only ever snaps between anchors, so
      // pulling the rest would be the entire sequence downloaded to be
      // never shown.
      if (reducedMotion) return;

      let next = 0;
      await Promise.all(
        Array.from({ length: LOAD_CONCURRENCY }, async () => {
          while (!cancelled && next < set.count) await loadFrame(next++);
        }),
      );
    })();

    /** One rAF, reading the container's live rect and painting from it in
     * the same frame — see the note on `progress` above for why this
     * replaces a scroll listener. It also subsumes the old resize handler:
     * a viewport change moves the rect, so the loop re-measures and
     * repaints without a separate listener that could fire out of step
     * with it. */
    let raf = 0;
    let lastDrawn = -1;
    const tick = () => {
      raf = requestAnimationFrame(tick);

      const rect = container.getBoundingClientRect();
      const span = rect.height - window.innerHeight;
      const p = span > 0 ? Math.max(0, Math.min(1, -rect.top / span)) : 0;
      progress.set(p);
      // Past the hero the canvas is display:none, so it has no box to
      // measure and nothing to paint.
      if (p >= 1) return;

      if (syncSize()) lastDrawn = -1;

      const target = reducedMotion
        ? segments[chapterAtProgress(segments, p)].frame
        : Math.round(frameAtProgress(segments, p));

      const anchor = computeAnchorX(p);
      if (target === lastDrawn && Math.abs(anchor - anchorXRef.current) <= 0.001) return;
      anchorXRef.current = anchor;
      lastDrawn = target;
      drawFrame(target);
    };
    raf = requestAnimationFrame(tick);

    return () => {
      cancelled = true;
      cancelAnimationFrame(raf);
      framesRef.current = [];
    };
  }, [reducedMotion, segments, progress]);

  return (
    <div ref={containerRef} className="hero-container is-scrub">
      <motion.canvas ref={canvasRef} className="hero-canvas" style={{ display: pastHeroDisplay }} />

      <motion.div
        className="hero-blackout"
        style={{ opacity: blackoutOpacity, display: pastHeroDisplay }}
        aria-hidden
      />

      {BEATS.map((beat, i) => (
        <motion.div
          key={beat.key}
          className="hero-beat"
          style={{ opacity: beatMotions[i].opacity, visibility: beatMotions[i].visibility }}
        >
          <span className="hero-beat-numeral font-display" aria-hidden>
            {beat.index}
          </span>
          <motion.div className="hero-beat-inner" style={{ y: beatMotions[i].y }}>
            <BeatCopy beat={beat} />
          </motion.div>
        </motion.div>
      ))}

      <motion.div
        className="hero-content"
        style={{ opacity: introOpacity, visibility: introVisibility }}
      >
        {/* One headline, one message — "Limit" is the only accent color in
            the whole hero, so it actually reads as emphasis instead of
            competing with a separate overline + tagline saying similar
            things in three different places. */}
        <HeroHeadline entered={entered} reducedMotion={reducedMotion} />
      </motion.div>

      <div className="hero-scroll-spacer" aria-hidden />
    </div>
  );
}

